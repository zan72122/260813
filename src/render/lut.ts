/**
 * 光弾性の色見本（アイソクロマティック LUT）。
 *
 * 直交ニコル（偏光板を90度で重ねた状態）では、力のかかっていない透明模型は真っ黒。
 * 力がかかるほど位相差がふえ、黒 → 青 → 緑 → 黄 → 赤 → 紫 …と虹が何周もする。
 * 次数が上がるほど色は淡くなる（実物と同じ）。
 * ここでは実写の並びを手で写し取った鍵色を線形補間して 1 次元テーブルにする。
 */

export const LUT_MAX_ORDER = 4;
const STEPS = 768;

type Key = [number, number, number, number]; // [order, r, g, b]

const KEYS: Key[] = [
  [0.0, 0, 0, 0],
  [0.1, 5, 8, 22],
  [0.2, 16, 26, 66],
  [0.3, 34, 62, 130],
  [0.4, 64, 132, 200],
  [0.5, 88, 196, 214],
  [0.6, 106, 220, 146],
  [0.72, 196, 232, 92],
  [0.82, 255, 224, 70],
  [0.92, 255, 158, 48],
  [1.0, 255, 88, 78],
  [1.1, 236, 58, 150],
  [1.2, 172, 70, 224],
  [1.32, 92, 110, 240],
  [1.45, 58, 190, 232],
  [1.58, 80, 226, 142],
  [1.72, 192, 236, 84],
  [1.85, 255, 220, 70],
  [1.95, 255, 150, 62],
  [2.05, 255, 96, 112],
  [2.16, 226, 82, 192],
  [2.3, 142, 112, 236],
  [2.45, 92, 182, 236],
  [2.6, 112, 222, 182],
  [2.78, 202, 232, 122],
  [2.92, 255, 216, 112],
  [3.05, 255, 162, 124],
  [3.2, 242, 132, 182],
  [3.4, 182, 152, 232],
  [3.6, 142, 202, 232],
  [3.8, 184, 226, 202],
  [4.0, 228, 232, 218],
];

function buildLut(): Uint8ClampedArray {
  const lut = new Uint8ClampedArray(STEPS * 3);
  let k = 0;
  for (let i = 0; i < STEPS; i++) {
    const n = (i / (STEPS - 1)) * LUT_MAX_ORDER;
    while (k < KEYS.length - 2 && n > KEYS[k + 1][0]) k++;
    const a = KEYS[k];
    const b = KEYS[k + 1];
    const span = b[0] - a[0];
    const t = span > 1e-6 ? Math.min(1, Math.max(0, (n - a[0]) / span)) : 0;
    // なめらかに繋いで縞のふちをやわらかく
    const s = t * t * (3 - 2 * t);
    lut[i * 3] = a[1] + (b[1] - a[1]) * s;
    lut[i * 3 + 1] = a[2] + (b[2] - a[2]) * s;
    lut[i * 3 + 2] = a[3] + (b[3] - a[3]) * s;
  }
  return lut;
}

export const FRINGE_LUT = buildLut();
export const LUT_SCALE = (STEPS - 1) / LUT_MAX_ORDER;
export const LUT_LAST = (STEPS - 1) * 3;
